"""Metadata catalog of public Max Planck Institute for Security and Privacy pages.

Hosts are www.mpi-sp.org and mpi-sp.org. Eligible pages are AI,
machine-learning, security-research, news, and publication HTML. A row keeps
the title, publisher, canonical URL, date, and rights label. Page bodies,
abstracts, PDFs, quotes, transcripts, and chart data are not stored. The live
URL is stored as confirmed; a different rel=canonical does not replace it.

Each stored URL was confirmed with one bounded GET that returned HTML and
stayed on those hosts. robots.txt for User-agent * states no disallow.
An HTML document served in place of robots.txt does not allow a fetch. A
Cloudflare challenge, a captcha, an authentication wall, a non-HTML shell,
a robots disallow, or a redirect off those hosts is not stored. An empty
entries list is valid when every fetch is blocked. Login walls, person
profiles, and other hosts are not stored. This module does not fetch and it
does not bypass a challenge, a captcha, authentication, or robots.

Rights stay unknown unless the page states a reuse licence.
``creative_commons_attribution`` means CC BY alone, including a
https://creativecommons.org/licenses/by/4.0/ URL. ``creative_commons`` means
CC0, CC BY-SA, or a permissive mix of those, including CC BY together with
CC0 or CC BY-SA. A sole CC BY-NC, CC BY-ND, CC BY-NC-SA, or CC BY-NC-ND keeps
that token. A hyphen is a word boundary, so CC BY does not match CC BY-NC and
licenses/by does not match licenses/by-nc. Two different restricted deeds stay
unknown. A software licence beside any Creative Commons deed stays unknown.
Two software licences stay unknown. A permissive anchor on a restricted deed
URL or a public-domain mark URL stays unknown. A CC0 anchor on a
publicdomain/mark URL stays unknown. A generic creativecommons.org/licenses
URL is not a deed: a missing slash, http, a www host, and a query string stay
on that generic path, and the anchor text does not count. Text elsewhere on
the page still counts. A specific deed URL still counts. A photo credit,
caption credit, or image credit that names someone else's licence does not
count, including Photo credit: UNDRR, CC BY-NC-ND 2.0 and Photo: UNDRR,
CC BY-NC-ND 2.0. A page licence stated outside that credit still counts.
The Public Domain Mark is not CC0. ``uk_ogl`` requires the British phrase
Open Government Licence. American spelling License stays unknown.
``us_government_work`` requires an explicit rights metadata field. ``mit``,
``apache-2.0``, and ``mpl-2.0`` stay their own tokens only for a sole
software licence. Bare MIT stays unknown. Licensed under the MIT License is
mit. Apache License, Version 2.0 is apache-2.0.

Updated, modified, and copyright years are not publication dates. Script,
style, and comment text does not count. A missing publication date stays
unknown. This module is not a belief collector. ``runner_wired`` stays false.
"""

